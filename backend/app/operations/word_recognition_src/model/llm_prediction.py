from .smolvlm_model import infer_sequence

def query_model(sequence_path):
    """
    Wrapper function for performing model inference on a given input sequence.

    Args:
        sequence_path (Path): Path to the JSON file containing the sequence of character entries,
                              including OCR text and image paths.

    Returns:
        str: The raw textual output generated by the language model.
    """
    return infer_sequence(sequence_path)

